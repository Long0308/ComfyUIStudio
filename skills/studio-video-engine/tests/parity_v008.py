"""Semantic parity of the engine's editorial build with the hand-built review cut (events + config).

Compared by meaning (frames, types, terms, hashes), never by raw bytes: the engine writes
episode-relative paths, its own class vocabulary (carry|cut) and engine type names.  What is
deliberately different is listed in :data:`INTENDED` and asserted to be exactly the observed
difference set, so a new, undocumented difference fails the parity test.

Usable as a script to print a JSON parity report:
``python -I tests/parity_v008.py <engine-events.json> <engine-config.json> [report.json]``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path, PureWindowsPath

REVIEW = ("production-local/JennieJoyKids-Story/04-milk-and-mom/editorial/review-hd-v008")
TYPE_NAMES = {"dip": "dip_white", "card-slide": "card_slide", "plate-in": "plate_in"}
INTENDED = {
    "transitions[].placement": "free-text placement notes are regenerated by the engine, not copied",
    "transitions[].class": "engine class is carry|cut (hand-built used descriptive labels such as 'hard cut')",
    "transitions[].continuity": "new field: continuity of the pair (agree|mismatch|unknown)",
    "transitions[].shows_both": "new field: explicit shows_both property of the transition type",
    "icon_events[].word_method": "new fields word_method + estimated mark how the pop time was measured",
    "transitions[].outgoing_tail.native_path": "episode-relative path (hand-built: absolute machine path)",
    "icon_events[].icon_path": "episode-relative path (hand-built: absolute machine path)",
    "ending.logo": "episode-relative path, no byte size (hand-built: absolute path + bytes)",
    "ending.end_plate": "speech-end fields renamed (ice_cream_speech_end_* -> speech_end_*), now measured by the engine",
    "config.total_frames": "engine total_frames = main film + end card (2580); hand-built kept 2520 + end_hold_frames",
    "config.wav_bindings[S06_B]": "engine binds the three receipt WAVs of S06_B1..3; hand-built used one concatenated WAV",
}


def _tail(tail: dict | None) -> dict | None:
    if tail is None:
        return None
    keys = ("shot", "native_sha256", "native_frames", "editorial_frames", "tail_frames_available",
            "tail_frames_needed", "last_native_index_used", "start_from_frame")
    kept = {key: tail[key] for key in keys}
    if "tail_output_frames" in tail:
        kept["tail_output_frames"] = tail["tail_output_frames"]
    return kept


def transition_view(row: dict, *, hand_built: bool) -> dict:
    kind = TYPE_NAMES.get(row["type"], row["type"]) if hand_built else row["type"]
    view = {key: row[key] for key in ("id", "boundary", "from", "to", "frames", "direction", "start",
                                      "end_exclusive", "motivation")}
    view["type"] = kind
    if hand_built:
        view["class"] = "carry" if row["class"].startswith("carry") or row["class"] == "continuous join" else "cut"
    else:
        view["class"] = row["class"]
    for key in ("out_frames", "in_frames", "schedule", "white_colour", "incoming_hidden_frames", "g_bridge",
                "iris_close_f", "logo_in_f", "disc_fade_start_f", "disc_fade_frames", "card1_ramp_frames"):
        if key in row:
            view[key] = row[key]
    view["outgoing_tail"] = _tail(row.get("outgoing_tail"))
    return view


def icon_view(row: dict) -> dict:
    keys = ("id", "shot", "word", "term", "icon", "icon_sha256", "word_start_frame", "frame", "frame_source",
            "hold_frames", "fade_frames", "total_frames", "lead_frames")
    return {key: row[key] for key in keys}


def ending_view(ending: dict, *, hand_built: bool) -> dict:
    plate = dict(ending["end_plate"])
    if hand_built:
        plate = {("speech_end_frame" if key == "ice_cream_speech_end_frame" else
                  "speech_end_s" if key == "ice_cream_speech_end_s" else
                  "speech_end_source" if key == "ice_cream_speech_end_source" else key): value
                 for key, value in plate.items()}
    return {"iris": ending["iris"], "logo_disc": ending["logo_disc"], "end_logo": ending["end_logo"],
            "end_plate": plate, "logo_sha256": ending["logo"]["sha256"]}


def _diff(label: str, ours, theirs, out: list[str]) -> None:
    if ours != theirs:
        out.append(f"{label}: engine {json.dumps(ours, sort_keys=True)[:300]} != hand-built "
                   f"{json.dumps(theirs, sort_keys=True)[:300]}")


def compare_events(engine: dict, hand: dict) -> list[str]:
    """Differences in events (transitions, icons, carries, ending, karaoke); empty = parity."""
    out: list[str] = []
    ours = {row["id"]: transition_view(row, hand_built=False) for row in engine["transitions"]}
    theirs = {row["id"]: transition_view(row, hand_built=True) for row in hand["transitions"]}
    if list(ours) != list(theirs):
        out.append(f"transition ids differ: {sorted(set(ours) ^ set(theirs))}")
    for key in theirs.keys() & ours.keys():
        for field in sorted(set(ours[key]) | set(theirs[key])):
            _diff(f"{key}.{field}", ours[key].get(field), theirs[key].get(field), out)
    _diff("icon_events", [icon_view(r) for r in engine["icon_events"]], [icon_view(r) for r in hand["icon_events"]], out)
    _diff("icon_terms_covered", engine["icon_terms_covered"], hand["icon_terms_covered"], out)
    _diff("karaoke_lines", engine["karaoke_lines"], hand["karaoke_lines"], out)
    _diff("ending", ending_view(engine["ending"], hand_built=False), ending_view(hand["ending"], hand_built=True), out)
    return out


def _name(path: str) -> str:
    return PureWindowsPath(path).name


def compare_config(engine: dict, hand: dict) -> list[str]:
    """Differences in the config (dialogue windows + words, cards, label, WAV starts)."""
    out: list[str] = []
    _diff("label", engine["label"], hand["label"], out)
    _diff("end_hold_frames", engine["end_hold_frames"], hand["end_hold_frames"], out)
    _diff("main_frames", engine["main_frames"], hand["total_frames"], out)
    keys = ("id", "start_frame", "duration_frames", "end_frame_exclusive")
    _diff("dialogue windows", [{k: d[k] for k in keys} for d in engine["dialogue"]],
          [{k: d[k] for k in keys} for d in hand["dialogue"]], out)
    _diff("dialogue words", [d["words"] for d in engine["dialogue"]], [d["words"] for d in hand["dialogue"]], out)
    _diff("outro cards", [(c["term"], c["start_frame"], c["duration_frames"], c["audio"]["sha256"])
                          for c in engine["outro_cards"]],
          [(c["term"], c["start_frame"], c["duration_frames"], c["audio"]["sha256"]) for c in hand["outro_cards"]], out)
    ours = {b["name"]: b for b in engine["wav_bindings"]}
    rows = {d["id"]: d for d in engine["dialogue"]}
    for entry in hand["dialogue"]:
        # every dialogue, S06_B included: the WAV the words were timed on is the hand-built WAV
        _diff(f"timing audio {entry['id']}", (rows[entry["id"]]["timing_audio"] or {}).get("sha256"),
              entry["audio"]["sha256"], out)
        if entry["id"] == "S06_B":
            segments = rows["S06_B"]["segments"]
            _diff("S06_B segments cover the hand-built window",
                  (segments[0]["start_frame"], sum(s["duration_frames"] for s in segments)),
                  (entry["start_frame"], entry["duration_frames"]), out)
            continue  # documented: three receipt WAVs instead of one concatenated WAV
        mine = ours[f"dlg {entry['id']}"]
        _diff(f"wav {entry['id']}", (mine["start_frame"], mine["sha256"], _name(mine["path"])),
              (entry["start_frame"] + entry["audio"]["offset_frames"], entry["audio"]["sha256"],
               _name(entry["audio"]["path"])), out)
    return out


def observed_intended(engine_events: dict, hand_events: dict, engine_config: dict, hand_config: dict) -> set[str]:
    """The keys of :data:`INTENDED` that actually differ in these documents (a stale entry shows up
    as a documented difference that no longer exists)."""
    found: set[str] = set()
    hand = {t["id"]: t for t in hand_events["transitions"]}
    for row in engine_events["transitions"]:
        other = hand[row["id"]]
        if row["placement"] != other["placement"]:
            found.add("transitions[].placement")
        if row["class"] != other["class"]:
            found.add("transitions[].class")
        if "continuity" in row and "continuity" not in other:
            found.add("transitions[].continuity")
        if "shows_both" in row and "shows_both" not in other:
            found.add("transitions[].shows_both")
        if (row.get("outgoing_tail") or {}).get("native_path") != (other.get("outgoing_tail") or {}).get("native_path"):
            found.add("transitions[].outgoing_tail.native_path")
    for row, other in zip(engine_events["icon_events"], hand_events["icon_events"]):
        if row["icon_path"] != other["icon_path"]:
            found.add("icon_events[].icon_path")
        if "word_method" in row and "word_method" not in other:
            found.add("icon_events[].word_method")
    if engine_events["ending"]["logo"] != hand_events["ending"]["logo"]:
        found.add("ending.logo")
    if engine_events["ending"]["end_plate"].keys() != hand_events["ending"]["end_plate"].keys():
        found.add("ending.end_plate")
    if engine_config["total_frames"] != hand_config["total_frames"]:
        found.add("config.total_frames")
    hand_s06 = next(d for d in hand_config["dialogue"] if d["id"] == "S06_B")["audio"]["sha256"]
    if hand_s06 not in {b["sha256"] for b in engine_config["wav_bindings"]}:
        found.add("config.wav_bindings[S06_B]")
    return found


def load_hand_built(repo_root: Path) -> tuple[dict, dict]:
    review = repo_root / REVIEW
    return (json.loads((review / "events-v008.json").read_text("utf-8")),
            json.loads((review / "config" / "review-config-v008.json").read_text("utf-8")))


def main(argv: list[str]) -> int:
    events = json.loads(Path(argv[1]).read_text("utf-8"))
    config = json.loads(Path(argv[2]).read_text("utf-8"))
    repo = Path(__file__).resolve().parents[4]
    hand_events, hand_config = load_hand_built(repo)
    diffs = compare_events(events, hand_events) + compare_config(config, hand_config)
    observed = observed_intended(events, hand_events, config, hand_config)
    if observed != set(INTENDED):
        diffs.append(f"documented differences != observed: {sorted(observed ^ set(INTENDED))}")
    report = {"compared": {"transitions": len(events["transitions"]), "icon_events": len(events["icon_events"]),
                           "karaoke_lines": len(events["karaoke_lines"]), "dialogue": len(config["dialogue"])},
              "differences": diffs, "documented_intended_differences": INTENDED,
              "verdict": "PARITY" if not diffs else "DIFFERS"}
    text = json.dumps(report, indent=2, ensure_ascii=False)
    if len(argv) > 3:
        Path(argv[3]).write_text(text + "\n", encoding="utf-8")
    print(text)
    return 0 if not diffs else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
